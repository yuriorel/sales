create table users (
    id              uuid primary key default uuidv7(),
    username        varchar(50)   not null unique,
    email           email_address not null unique,
    password_hash   varchar(100),
    auth_provider   varchar(10)   not null default 'LOCAL' check (auth_provider in ('LOCAL', 'OAUTH2')),
    external_id     varchar(255) unique,
    roles           varchar(20)[] not null default '{CUSTOMER}',
    default_address postal_address,
    preferences     jsonb         not null default '{}',
    created_at      timestamptz   not null default now(),
    check ((auth_provider = 'LOCAL' and password_hash is not null)
        or (auth_provider = 'OAUTH2' and external_id is not null))
);

create table categories (
    id          bigint generated by default as identity primary key,
    slug        varchar(60)  not null unique check (slug ~ '^[a-z0-9-]+$'),
    name        varchar(100) not null unique,
    description text
);

create table products (
    id             bigint generated by default as identity primary key,
    sku            sku_code      not null unique,
    category_id    bigint        not null references categories (id),
    name           varchar(200)  not null,
    brand          varchar(100),
    description    text          not null,
    price          money_amount  not null,
    currency       currency_code not null default 'USD',
    rating         rating,
    tags           text[]        not null default '{}',
    image_urls     text[]        not null default '{}',
    dimensions     dimensions_cm,
    attributes     jsonb         not null default '{}',
    user_guide     text          not null,
    guide_sections text[]        not null default '{}',
    search_vector  tsvector generated always as (
        setweight(to_tsvector('english', name), 'A') ||
        setweight(to_tsvector('english', coalesce(brand, '')), 'B') ||
        setweight(to_tsvector('english', description), 'C') ||
        setweight(to_tsvector('english', user_guide), 'D')
    ) stored,
    version        bigint        not null default 0,
    created_at     timestamptz   not null default now(),
    updated_at     timestamptz   not null default now()
);

create table inventory (
    product_id bigint primary key references products (id) on delete cascade,
    quantity   integer     not null check (quantity >= 0),
    updated_at timestamptz not null default now()
);

create table product_guide_chunks (
    id          bigint generated always as identity primary key,
    product_id  bigint       not null references products (id) on delete cascade,
    chunk_index integer      not null,
    content     text         not null,
    metadata    jsonb        not null default '{}',
    embedding   vector(1536) not null,
    unique (product_id, chunk_index)
);

create table carts (
    id         uuid primary key default uuidv7(),
    user_id    uuid        not null unique references users (id) on delete cascade,
    updated_at timestamptz not null default now()
);

create table cart_items (
    cart_id    uuid         not null references carts (id) on delete cascade,
    product_id bigint       not null references products (id) on delete cascade,
    quantity   positive_qty not null,
    primary key (cart_id, product_id)
);

create table orders (
    id               uuid primary key default uuidv7(),
    user_id          uuid           not null references users (id),
    status           order_status   not null default 'PENDING',
    total            money_amount   not null,
    currency         currency_code  not null,
    shipping_address postal_address not null,
    status_history   jsonb          not null default '[]' check (jsonb_typeof(status_history) = 'array'),
    created_at       timestamptz    not null default now(),
    updated_at       timestamptz    not null default now()
);

create table order_items (
    order_id     uuid         not null references orders (id) on delete cascade,
    product_id   bigint       not null references products (id),
    product_name varchar(200) not null,
    unit_price   price_tag    not null,
    quantity     positive_qty not null,
    primary key (order_id, product_id)
);

create table payments (
    id               uuid primary key default uuidv7(),
    order_id         uuid         not null unique references orders (id) on delete cascade,
    amount           money_amount not null,
    status           varchar(10)  not null check (status in ('APPROVED', 'DECLINED')),
    reference        varchar(64),
    gateway_response jsonb        not null default '{}',
    created_at       timestamptz  not null default now()
);

create table processed_events (
    event_id     uuid primary key,
    event_type   varchar(64) not null,
    payload      jsonb       not null,
    processed_at timestamptz not null default now()
);

create index products_search_vector_idx on products using gin (search_vector);
create index products_tags_idx on products using gin (tags);
create index products_attributes_idx on products using gin (attributes jsonb_path_ops);
create index products_category_idx on products (category_id);
create index product_guide_chunks_embedding_idx on product_guide_chunks using hnsw (embedding vector_cosine_ops);
create index orders_user_created_idx on orders (user_id, created_at desc);
